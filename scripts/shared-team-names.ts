// Regenerates src/lib/shared-team-names.ts: every team name the Stats API gives to more than one
// team (current and past, every sport), so `page_label` can tell them apart without an extra
// request per pageview. Run with `bun scripts/shared-team-names.ts`, then `bun run format`.
import { writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

type Team = { name?: string; sport?: { abbreviation?: string } }

const res = await fetch(
	'https://statsapi.mlb.com/api/v1/teams?activeStatus=B&hydrate=sport&fields=teams,name,sport,abbreviation',
)
if (!res.ok) throw new Error(`Stats API: ${res.status}`)
const { teams } = (await res.json()) as { teams: Team[] }

const sportsByName = new Map<string, string[]>()
for (const { name, sport } of teams) {
	if (!name) continue
	sportsByName.set(name, [...(sportsByName.get(name) ?? []), sport?.abbreviation ?? ''])
}

const shared = Object.fromEntries(
	[...sportsByName]
		.filter(([, sports]) => sports.length > 1)
		.sort(([a], [b]) => a.localeCompare(b))
		.map(([name, sports]) => [name, sports.sort()]),
)

writeFileSync(
	resolve(import.meta.dir, '../src/lib/shared-team-names.ts'),
	`// Generated by scripts/shared-team-names.ts; don't edit by hand.

/**
 * Team names the Stats API gives to more than one team, with the sport abbreviation of each
 * team that has it (repeated when two teams in one sport share the name)
 */
export const SHARED_TEAM_NAMES: Record<string, string[]> = ${JSON.stringify(shared)}
`,
)

console.log(`${Object.keys(shared).length} shared team names`)
